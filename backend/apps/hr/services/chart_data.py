def _dept(name, color, head_title, head, sections=(), positions=(), channel=""):
    return {
        "name": name, "kind": "department", "color": color, "channel": channel,
        "positions": [(head_title, head, True), *positions],
        "children": list(sections),
    }


def _section(name, positions, children=(), channel=""):
    return {
        "name": name, "kind": "section", "channel": channel,
        "positions": list(positions), "children": list(children),
    }


